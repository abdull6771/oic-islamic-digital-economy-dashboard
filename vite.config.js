import { defineConfig, loadEnv } from "vite";
import react from "@vitejs/plugin-react";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { createInternalAuthMiddleware } from "./server/auth.js";

const root = fileURLToPath(new URL(".", import.meta.url));
const internalViews = ["WhatIfCalculator", "CustomIndexBuilder", "PeerLearning", "PolicyRecommendations", "DataQualityExplorer", "StatisticalAnalysis", "Methodology", "ReportDownloads", "UpdateHistory"];

export default defineConfig(({ mode, command }) => {
  // Only these two public values enter the client. Passwords stay server-side.
  const env = loadEnv(mode, root, "");
  const edition = ["public", "full"].includes(mode) ? mode : env.SITE_EDITION || "public";
  if (!["public", "full"].includes(edition)) throw new Error("SITE_EDITION must be public or full.");
  const contactEmail = env.CONTACT_EMAIL || "devbabura@gmail.com";
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(contactEmail)) throw new Error("CONTACT_EMAIL must be an email address.");
  const guard = () => createInternalAuthMiddleware({ edition, env });
  let writesBuild = false;
  return {
    plugins: [react(), {
      name: "site-edition-boundary",
      configResolved(config) { writesBuild = config.build.write !== false; },
      buildStart() {
        if (command === "build" && writesBuild) writeFileSync(new URL("./server/build-edition.js", import.meta.url), `// Generated by the selected edition build.\nexport const BUILD_EDITION = ${JSON.stringify(edition)};\n`);
      },
      generateBundle() {
        this.emitFile({ type: "asset", fileName: "edition.json", source: JSON.stringify({
          edition,
          datasetSha256: createHash("sha256").update(readFileSync(new URL("./src/data/adei-dataset.json", import.meta.url))).digest("hex"),
        }) + "\n" });
      },
      configureServer(server) { server.middlewares.use(guard()); },
      configurePreviewServer(server) {
        const marker = JSON.parse(readFileSync(resolve(root, server.config.build.outDir, "edition.json"), "utf8"));
        if (marker.edition !== edition) throw new Error("The preview edition does not match the selected build.");
        server.middlewares.use(guard());
      },
    }],
    resolve: { alias: { "#edition-views": fileURLToPath(new URL(`./src/views/registry.${edition}.js`, import.meta.url)) } },
    define: { __SITE_EDITION__: JSON.stringify(edition), __CONTACT_EMAIL__: JSON.stringify(contactEmail) },
    cacheDir: `node_modules/.vite-${edition}`,
    server: { host: "127.0.0.1", fs: { deny: [".env", ".env.*", "*.{crt,pem,key}", "**/.git/**", "**/server/**", "**/middleware.js", ...(edition === "public" ? internalViews.map((name) => `**/src/views/${name}.jsx`).concat(["**/src/lib/country-reports.js", "**/src/lib/what-if.js", "**/src/views/registry.full.js"]) : [])] } },
  };
});
